"""
ตัวเข้ารหัสรหัสผ่าน (password hasher) แบบเบา สำหรับรหัสชั่วคราวที่ระบบสุ่มตอนนำเข้า CSV (ขั้น 2.4)

ทำไมต้องมี (ผู้ใช้เลือกแบบ ก 2026-10-12):
- ตัวหลักของ Django (PBKDF2 1,000,000 รอบ) ใช้ ~0.4 วินาทีต่อรหัสบนเครื่องพัฒนา
  → นำเข้า 500 คน ≈ 3.5 นาที และบนเครื่องฟรีตอน deploy (CPU ~0.1 ตัว) ช้ากว่านี้มากจนคำขอถูกตัด
- ความช้านั้นมีไว้กันการเดารหัสที่ "คนตั้งเอง" (เดาง่าย) — รหัสที่ระบบสุ่ม 12 ตัวจากอักขระ 56 แบบ
  (≈ 2^69 แบบ) เดาไม่ได้อยู่แล้วแม้เข้ารหัสด้วยรอบน้อยกว่า

ทำงานอย่างไร:
- ลงทะเบียนเป็นตัว "รอง" ใน settings.PASSWORD_HASHERS (ตัวแรกยังเป็นตัวหลักของ Django)
- ใช้เฉพาะตอนนำเข้า CSV: make_password(รหัส, hasher=TemporaryPasswordHasher.algorithm)
- ผู้ใช้เข้าสู่ระบบครั้งแรกด้วยรหัสนี้ → check_password() ของ Django เห็นว่าไม่ใช่ตัวหลัก
  → เข้ารหัสใหม่ด้วยตัวหลักแล้วบันทึกทับอัตโนมัติ (ไม่ต้องเขียนโค้ดเพิ่ม)
- สร้างทีละคน / รีเซ็ตรหัส / เปลี่ยนรหัสเอง ยังใช้ตัวหลักเสมอ
"""

from django.contrib.auth.hashers import PBKDF2PasswordHasher


class TemporaryPasswordHasher(PBKDF2PasswordHasher):
    """PBKDF2-SHA256 รอบน้อย — ชื่อ algorithm ต่างจากตัวหลัก Django จึงรู้ว่าต้องเปลี่ยนตอน login"""

    algorithm = "pbkdf2_sha256_temp"
    # น้อยกว่าตัวหลัก 500 เท่า (1,000,000 → 2,000) — วัดจริงบนเครื่องพัฒนา (2026-10-12):
    #   ~0.7 มิลลิวินาทีต่อรหัส ; นำเข้า 500 แถวทั้งคำขอ ~1.2 วินาที
    #   (10,000 รอบ = ~3.9 วินาที → บนเครื่องฟรีที่ช้ากว่า ~10 เท่า เสี่ยงเกินเวลารอคำขอ 30 วินาที)
    # ยังปลอดภัย: รหัสสุ่ม ≈ 2^69 แบบ — การ์ดจอแรง 1 ใบเดาด้วยรอบเท่านี้ได้หลักล้านครั้ง/วินาที
    #   → ต้องใช้เวลาระดับล้านปีกว่าจะเจอ
    iterations = 2_000
